import { useCallback, useEffect, useRef, useState } from 'react';
import { registerSW } from 'virtual:pwa-register';

interface BeforeInstallPromptEvent extends Event {
  prompt: () => Promise<void>;
  userChoice: Promise<{ outcome: 'accepted' | 'dismissed' }>;
}

const isStandalone = () =>
  window.matchMedia('(display-mode: standalone)').matches ||
  (window.navigator as unknown as { standalone?: boolean }).standalone === true;

const isIos = () =>
  /iphone|ipad|ipod/i.test(navigator.userAgent) ||
  (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);

export interface PwaApi {
  canInstall: boolean;
  /** iOS/iPadOS has no install prompt — show manual instructions instead. */
  needsManualInstall: boolean;
  installed: boolean;
  install: () => Promise<boolean>;
  offline: boolean;
  updateReady: boolean;
  applyUpdate: () => Promise<void>;
  dismissUpdate: () => void;
}

/**
 * Install prompt, offline detection and "new version available" handling for
 * the service worker generated by vite-plugin-pwa.
 */
export function usePwa(): PwaApi {
  const [installEvent, setInstallEvent] = useState<BeforeInstallPromptEvent | null>(null);
  const [installed, setInstalled] = useState(isStandalone);
  const [offline, setOffline] = useState(!navigator.onLine);
  const [updateReady, setUpdateReady] = useState(false);
  const updateRef = useRef<((reloadPage?: boolean) => Promise<void>) | null>(null);

  useEffect(() => {
    const onPrompt = (event: Event) => {
      event.preventDefault();
      setInstallEvent(event as BeforeInstallPromptEvent);
    };
    const onInstalled = () => {
      setInstalled(true);
      setInstallEvent(null);
    };
    const onOnline = () => setOffline(false);
    const onOffline = () => setOffline(true);

    window.addEventListener('beforeinstallprompt', onPrompt);
    window.addEventListener('appinstalled', onInstalled);
    window.addEventListener('online', onOnline);
    window.addEventListener('offline', onOffline);
    return () => {
      window.removeEventListener('beforeinstallprompt', onPrompt);
      window.removeEventListener('appinstalled', onInstalled);
      window.removeEventListener('online', onOnline);
      window.removeEventListener('offline', onOffline);
    };
  }, []);

  useEffect(() => {
    updateRef.current = registerSW({
      immediate: true,
      onNeedRefresh: () => setUpdateReady(true),
    });
  }, []);

  const install = useCallback(async () => {
    if (!installEvent) return false;
    await installEvent.prompt();
    const choice = await installEvent.userChoice;
    if (choice.outcome === 'accepted') {
      setInstalled(true);
      setInstallEvent(null);
      return true;
    }
    return false;
  }, [installEvent]);

  const applyUpdate = useCallback(async () => {
    await updateRef.current?.(true);
    setUpdateReady(false);
  }, []);

  const dismissUpdate = useCallback(() => setUpdateReady(false), []);

  return {
    canInstall: !!installEvent && !installed,
    needsManualInstall: isIos() && !installed,
    installed,
    install,
    offline,
    updateReady,
    applyUpdate,
    dismissUpdate,
  };
}
